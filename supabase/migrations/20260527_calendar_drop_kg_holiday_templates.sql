-- В календаре сотрудников отмечаем только то, что влияет на работу.
-- Праздники с режимом «работаем как обычно» (event_type='holiday') убираем,
-- чтобы не перегружать календарь: Рождество, День защитника, Праздник труда,
-- День Конституции, День независимости, Дни истории и памяти.
-- Остаются сокращённые дни (short_day) и нерабочие (closed) + айты (разовые).
DELETE FROM public.franchise_calendar_templates
WHERE country_id = 'kg' AND event_type = 'holiday';
