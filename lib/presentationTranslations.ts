export function translatePresentationText(source: string): string {
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return source;
  const [, leading, value, trailing] = match;
  if (!value) return source;

  const exact = EN[value];
  if (exact) return `${leading}${exact}${trailing}`;

  let translated = value;
  for (const [from, to] of PREFIXES) {
    if (translated.includes(from)) translated = translated.replace(from, to);
  }

  translated = translated
    .replace(/([\d\s,.]+)\s+сом(?=\s|$|[.,])/g, '$1 KGS')
    .replace(/([\d\s,.]+)\s+с(?=\s|$|[.,])/g, '$1 KGS')
    .replace(/(\d+)\s+из\s+(\d+)/g, '$1 of $2')
    .replace(/(\d+)\s+заказ(?:ов|а)?(?=\s|$|[.,])/g, '$1 orders')
    .replace(/(\d+)\s+заяв(?:ок|ки|ка)(?=\s|$|[.,])/g, '$1 applications')
    .replace(/(\d+)\s+нов(?:ых|ая|ые)(?=\s|$|[.,])/g, '$1 new')
    .replace(/(\d+)\s+дн\.?(?=\s|$|[,])/g, '$1 days')
    .replace(/(\d+)\s+мин\.?(?=\s|$|[,])/g, '$1 min')
    .replace(/(\d+)\s+ч\.?(?=\s|$|[,])/g, '$1 hr')
    .replace(/(\d+)\s+шт\.?(?=\s|$|[,])/g, '$1 pcs')
    .replace(/(\d+)-я\s+неделя/g, 'Week $1')
    .replace(/за\s+10\s+мин(?=\s|$|[.,])/g, 'within 10 min')
    .replace(/нет данных за пред\. мес\./g, 'no previous-month data')
    .replace(/нет номера/g, 'no phone number')
    .replace(/Пока нет заявок/g, 'No applications yet');

  return translated === value ? source : `${leading}${translated}${trailing}`;
}

export type PresentationPrivacyKind =
  | 'customer'
  | 'employee'
  | 'person'
  | 'phone'
  | 'email'
  | 'private';

const CUSTOMER_LABELS = /^(?:клиент|клиенты|customer|customers|patient)$/i;
const EMPLOYEE_LABELS = /^(?:сотрудник|сотрудники|employee|employees|продавец|seller|sales associate|фио|full name)$/i;
const PHONE_LABELS = /^(?:телефон|номер телефона|phone|phone number|mobile)$/i;
const EMAIL_LABELS = /^(?:email|e-mail|электронная почта)$/i;
const PRIVATE_FIELD_LABELS = /^(?:pin|пароль|password|логин|login|адрес|address|рецепт|prescription|right(?: eye)? \(od\)|left(?: eye)? \(os\)|правый(?: глаз)? \(od\)|левый(?: глаз)? \(os\))$/i;

/** Classifies only explicit labels; generic labels such as "Name" stay untouched. */
export function getPresentationPrivacyKind(label: string): PresentationPrivacyKind | null {
  const normalized = label.replace(/\s+/g, ' ').trim().replace(/:$/, '');
  if (CUSTOMER_LABELS.test(normalized)) return 'customer';
  if (EMPLOYEE_LABELS.test(normalized)) return 'employee';
  if (PHONE_LABELS.test(normalized)) return 'phone';
  if (EMAIL_LABELS.test(normalized)) return 'email';
  if (PRIVATE_FIELD_LABELS.test(normalized)) return 'private';
  return null;
}

function stablePrivacyNumber(value: string): string {
  let hash = 2166136261;
  for (const char of value.toLocaleLowerCase('ru-RU')) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 16777619);
  }
  return String((hash >>> 0) % 900 + 1).padStart(3, '0');
}

function looksLikePersonName(value: string): boolean {
  const normalized = value.trim();
  if (!normalized || normalized === '—') return false;
  if (/^(?:Customer|Employee|Person) \d{3}$/i.test(normalized)) return false;
  return /^[\p{L}][\p{L}'’.,-]*(?:\s+[\p{L}][\p{L}'’.,-]*){0,3}$/u.test(normalized);
}

/** Produces a deterministic display alias without modifying the underlying value. */
export function pseudonymizePresentationName(
  source: string,
  kind: 'customer' | 'employee' | 'person',
): string {
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return source;
  const [, leading, value, trailing] = match;
  if (!looksLikePersonName(value)) return source;
  const label = kind === 'customer' ? 'Customer' : kind === 'employee' ? 'Employee' : 'Person';
  return `${leading}${label} ${stablePrivacyNumber(value)}${trailing}`;
}

const PHONE_CANDIDATE = /\+?\d[\d\s().-]{7,}\d/g;
const EMAIL_CANDIDATE = /[\w.!#$%&'*+/=?^`{|}~-]+@[\w.-]+\.[A-Za-z]{2,}/g;

/** Masks visible phone numbers and email addresses while preserving non-contact numbers. */
export function maskPresentationContacts(source: string): string {
  return source
    .replace(EMAIL_CANDIDATE, (email) => `contact-${stablePrivacyNumber(email)}@example.invalid`)
    .replace(PHONE_CANDIDATE, (candidate) => {
      const digits = candidate.replace(/\D/g, '');
      if (digits.length < 9) return candidate;
      const lastTwo = digits.slice(-2);
      if (!candidate.trimStart().startsWith('+')) return `*** *** ** ${lastTwo}`;
      const countryLength = digits.startsWith('996') || digits.startsWith('998') ? 3 : digits.startsWith('7') ? 1 : Math.min(3, digits.length - 7);
      return `+${digits.slice(0, Math.max(1, countryLength))} *** ** ${lastTwo}`;
    });
}

/** Applies a display-only privacy transform to one already-rendered field value. */
export function privatizePresentationText(
  source: string,
  kind?: PresentationPrivacyKind | null,
): string {
  const contactsMasked = maskPresentationContacts(source);
  if (kind === 'customer' || kind === 'employee' || kind === 'person') {
    return pseudonymizePresentationName(contactsMasked, kind);
  }
  if (kind === 'phone') {
    return contactsMasked === source && source.trim() !== '—' ? 'Private phone' : contactsMasked;
  }
  if (kind === 'email') {
    return contactsMasked === source && source.trim() !== '—' ? 'Private email' : contactsMasked;
  }
  if (kind === 'private' && source.trim() !== '—') return '•••';
  return contactsMasked;
}
